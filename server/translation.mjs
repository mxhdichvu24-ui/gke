export const translationConfigured=()=>Boolean(process.env.GOOGLE_TRANSLATE_API_KEY);
const sourceFields=['title','excerpt','body','alt','seoTitle','seoDescription'];
const limits={title:180,excerpt:600,body:200000,alt:200,seoTitle:180,seoDescription:320};
const decode=text=>String(text).replace(/&#(x[0-9a-f]+|\d+);|&(amp|lt|gt|quot|apos);/gi,(_,n,key)=>{if(key)return{amp:'&',lt:'<',gt:'>',quot:'"',apos:"'"}[key.toLowerCase()];const v=n[0].toLowerCase()==='x'?parseInt(n.slice(1),16):Number(n);return v>0&&v<=0x10ffff?String.fromCodePoint(v):''});

// Send only text nodes. Markdown structure, URLs and code never leave their
// original positions and are never regenerated by the translation service.
export function planTranslation(source){
 const texts=[];
 const add=value=>{if(!value||!value.trim())return()=>value;const i=texts.length;texts.push(value);return translated=>translated[i]};
 const inline=line=>{
  const regex=/!\[([^\]\n]*)\]\(([^)\s]+)\)|\[([^\]\n]+)\]\(([^)\s]+)\)|`([^`\n]+)`|\*\*([^*\n]+)\*\*|\*([^*\n]+)\*/g,parts=[];let end=0;
  for(const m of line.matchAll(regex)){parts.push(add(line.slice(end,m.index)));end=m.index+m[0].length;
   if(m[1]!==undefined){const alt=add(m[1]);parts.push(t=>`![${alt(t)}](${m[2]})`)}
   else if(m[3]){const label=add(m[3]);parts.push(t=>`[${label(t)}](${m[4]})`)}
   else if(m[5])parts.push(()=>m[0]);else{const label=add(m[6]||m[7]),wrap=m[6]?'**':'*';parts.push(t=>wrap+label(t)+wrap)}
  }
  parts.push(add(line.slice(end)));return t=>parts.map(p=>p(t)).join('');
 };
 const fields={};
 for(const key of sourceFields){
  const value=String(source[key]||'');if(key!=='body'){fields[key]=add(value);continue}
  let code=false;const lines=value.split('\n').map(line=>{if(line.startsWith('```')){code=!code;return()=>line}if(code)return()=>line;const prefix=line.match(/^(?:#{1,4}\s+|[-*]\s+|\d+\.\s+|>\s+)/)?.[0]||'',render=inline(line.slice(prefix.length));return t=>prefix+render(t)});fields[key]=t=>lines.map(line=>line(t)).join('\n');
 }
 return{texts,restore:translated=>Object.fromEntries(sourceFields.map(k=>[k,fields[k](translated)]))};
}
export async function translateTextNodes(texts,target,fetcher=fetch){
 if(!translationConfigured())fail('translation_unconfigured',503);
 const output=[];
 for(let start=0;start<texts.length;start+=100){
  const batch=texts.slice(start,start+100);
  const q=batch.map(text=>escapeHtml(text).replace(/\b(?:GKE(?: Logistics)?|USPS|UPS|DHL|UniUni|Hanjin|TikTok|FBA|DDP)\b/g,value=>`<span class="notranslate">${value}</span>`));
  const response=await fetcher('https://translation.googleapis.com/language/translate/v2?key='+encodeURIComponent(process.env.GOOGLE_TRANSLATE_API_KEY),{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({q,source:'vi',target:target==='zh'?'zh-CN':'en',format:'html',model:'nmt'}),signal:AbortSignal.timeout(25000)});
  if(!response.ok)fail('translation_provider_unavailable',503);const data=await response.json(),translated=data.data?.translations;
  if(!Array.isArray(translated)||translated.length!==q.length||translated.some(v=>typeof v.translatedText!=='string'||v.translatedText.length>100000))fail('invalid_translation_response',502);
  output.push(...translated.map(v=>decode(v.translatedText.replace(/<[^>]*>/g,''))));
 }
 return output;
}
const slug=value=>value.toLowerCase().replaceAll('đ','d').normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'').slice(0,110).replace(/-$/,'');
export async function translateArticle(id,revision,actor,{fetcher=fetch}={}){
 const row=await getDocument('articles',id);if(!row)fail('not_found',404);if(row.revision!==revision)fail('conflict',409);
 const value=structuredClone(row.value),source=value.translations?.vi?.draft||value.translations?.vi;
 if(!source?.title||!source.body)fail('translation_source_incomplete');
 const sourceHash=createHash('sha256').update(JSON.stringify([...sourceFields,'cover','shareImage'].map(k=>source[k]||''))).digest('hex');
 const targets=['en','zh'].filter(lang=>{const tr=value.translations[lang]?.draft||value.translations[lang];return !(tr?.translationSourceHash===sourceHash)&&(!tr?.body||tr.machineTranslated===true)});
 if(!targets.length)return{row,skipped:true};
 const plan=planTranslation(source);if(plan.texts.join('').length>30000)fail('translation_source_too_large',413);
 const translations={};
 for(const lang of targets){const translated=plan.restore(await translateTextNodes(plan.texts,lang,fetcher));for(const k of sourceFields)translated[k]=translated[k].slice(0,limits[k]);translations[lang]=translated;}
 for(const lang of targets){const old=value.translations[lang],draft=old?.draft||old;
  const translated={...translations[lang],cover:source.cover||'',shareImage:source.shareImage||'',status:'draft',slug:draft?.slug||slug(translations.en?.title||source.slug||source.title)+(lang==='zh'?'-zh':''),publishedAt:old?.publishedAt||null,updatedAt:old?.updatedAt||null,machineTranslated:true,translationSourceHash:sourceHash};
  if(['published','hidden'].includes(old?.status))value.translations[lang]={...old,draft:translated};else value.translations[lang]=translated;
 }
 // CAS runs again after the external call; a newer human edit always wins.
 return{row:await saveDocument('articles',id,value,revision,actor),translated:targets};
}
